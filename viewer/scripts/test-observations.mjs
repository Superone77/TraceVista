import assert from 'node:assert/strict';
import { stripTypeScriptTypes } from 'node:module';
import { readFileSync } from 'node:fs';
const code = stripTypeScriptTypes(readFileSync(new URL('../src/trajectory/model.ts',import.meta.url),'utf8'));
const {parseGraph, observationsFor} = await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const fixture = JSON.parse(readFileSync(new URL('./fixtures/parser.agent-state.json',import.meta.url),'utf8'));
const original = JSON.stringify(fixture);
const g = parseGraph(fixture);
assert.equal(new Set(g.observations.map(o=>o.kind)).size,7);
assert.equal(new Set(g.observations.filter(o=>o.kind==='skill').map(o=>o.facts.load_method)).size,3);
assert.equal(new Set(g.observations.filter(o=>o.kind==='measurement').map(o=>o.facts.scope)).size,4);
assert.equal(JSON.stringify(fixture),original,'Parsing must not mutate evidence');
assert(observationsFor(g,'s0').some(o=>o.id==='o-trial'));
assert(!observationsFor(g,'a0').some(o=>o.id==='o-trial'),'Observations must stay in scope');
function rejects(edit) { const v=structuredClone(fixture); edit(v); assert.throws(()=>parseGraph(v)); }
rejects(v=>v.observations[0].events=['fabricated']);
rejects(v=>v.observations[0].subjects=['fabricated']);
rejects(v=>v.observations[0].id='s0');
rejects(v=>v.observations.find(o=>o.id==='o-material').facts.after_code='different-code');
rejects(v=>delete v.observations.find(o=>o.id==='o-todo-external').facts.reason);
rejects(v=>v.observations.find(o=>o.id==='o-performance').facts.outcome='pass');
rejects(v=>v.observations.find(o=>o.id==='o-independent_score').facts.value=true);
rejects(v=>v.observations.find(o=>o.id==='o-skill-read').artifacts=['missing']);
rejects(v=>v.observations.find(o=>o.id==='o-kr').facts.resource='unrelated.md');
rejects(v=>v.observations.find(o=>o.id==='o-todo-done').facts.task_key='other-task');
rejects(v=>v.observationLinks.push({source:'o-trial',target:'o-step',relation:'contains',reason:'cycle',events:['e1']}));
const legacy=structuredClone(fixture); delete legacy.observations; delete legacy.observationLinks;
assert.equal(parseGraph(legacy).actions.length,g.actions.length,'Legacy files remain supported');
console.log('PASS: seven neutral record types, scope, original retention, reference/identity validation, review code proof, task reasons, status/metric separation, relationship integrity, hierarchy cycles, legacy compatibility');
